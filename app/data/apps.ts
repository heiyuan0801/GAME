export interface Review {
  id: string
  title: string
  body: string
  rating: number
  date: string
  author: string
  helpful: number
  response?: { body: string; date: string }
}

export interface Shot {
  kind: 'chat' | 'gallery' | 'stats' | 'list' | 'camera' | 'map' | 'music' | 'cards' | 'board'
  caption: string
  tint: string
}

export interface AppVideo {
  id: string
  title: string
  caption: string
  duration: string
  url: string
  badge?: string
  poster?: string
}

