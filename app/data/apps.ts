export const byId = (id: string) => APPS.find((a) => a.id === id)

export const byChart = (kind: 'free' | 'paid' | 'grossing') =>
  APPS.filter((a) => a.chart[kind] != null).sort((a, b) => a.chart[kind]! - b.chart[kind]!)

export const topFree = (n = 10) => byChart('free').slice(0, n)
