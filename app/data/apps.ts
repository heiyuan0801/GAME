export const ratingBars = (app: AppItem) => {
  // Deterministic, plausible distribution derived from the app's own rating.
  const w = [0.78, 0.14, 0.045, 0.02, 0.015]
  const shift = (5 - app.rating) * 0.5
  const raw = w.map((v, i) => Math.max(0.004, v + (i === 0 ? -shift : shift / 4)))
  const total = raw.reduce((a, b) => a + b, 0)
  return raw.map((v) => v / total)
}

export function getAppVideos(app: AppItem): AppVideo[] {
  if (app.videos && app.videos.length > 0) {
    return app.videos
  }
  const isGame =
    app.category === 'Games' ||
    app.category === 'Adventure' ||
    app.category === 'Racing' ||
    Boolean(app.chart.grossing)
  return [
    {
      id: `${app.id}-preview-1`,
      title: `${app.name} — ${isGame ? 'Official Gameplay Showcase' : 'Feature Walkthrough'}`,
      caption: `Take a closer look at ${app.name}'s intuitive controls and standout features.`,
      duration: '0:35',
      url: isGame ? '/videos/preview-game.mp4' : '/videos/preview-app.mp4',
      badge: isGame ? 'Gameplay Trailer' : 'App Preview',
    },
  ]
}

